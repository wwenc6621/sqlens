const en: Record<string, string> = {};

const dicts: Record<Locale, Record<string, string>> = { en, zh };

/** Translate a user-facing string for the current webview locale.
 *  Supports `{0}`, `{1}`... placeholders filled from the extra arguments. */
export function t(key: string, ...args: unknown[]): string {
  let text: string = locale === 'en' ? key : (dicts[locale][key] ?? key);
  args.forEach((arg, i) => {
    text = text.replace(new RegExp(`\\{${i}\\}`, 'g'), String(arg));
  });
  return text;
}

export const i18n = { locale, t };

