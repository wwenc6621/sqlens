/**
 * i18n for the webview (React) side.
 *
 * The extension host injects the VS Code display language into
 * `window.__LOCALE__` when building the webview HTML. Translation
 * dictionaries live here; missing keys fall back to the English text.
 */

export type Locale = 'en' | 'zh';

declare global {
  interface Window {
    __LOCALE__?: string;
  }
}

function detectLocale(): Locale {
  const raw = (typeof window !== 'undefined' && window.__LOCALE__) || 'en';
  return raw.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

